/**
 * sync-icon-colors — generates icons.css and ICON_COLORS/IconColor from comete-design-tokens.
 *
 * Reads the compiled CSS from @aexae/comete-design-tokens, extracts all `--icon-*`
 * custom properties, and generates:
 *   - src/styles/icons.css   (CSS classes mapping color prop → token)
 *   - Patches src/types.ts   (ICON_COLORS const list + IconColor derived type)
 *
 * Run: pnpm sync-colors
 */

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const TOKENS_CSS_PATH = resolve(
  import.meta.dirname,
  "../../comete-design-tokens/build/css/comete-tokens.css",
);
const ICONS_CSS_PATH = resolve(import.meta.dirname, "../src/styles/icons.css");
const TYPES_PATH = resolve(import.meta.dirname, "../src/types.ts");

// ---------------------------------------------------------------------------
// 1. Parse token names from CSS

const css = readFileSync(TOKENS_CSS_PATH, "utf-8");

// Match all `--icon-*:` declarations (deduplicate via Set)
const tokenRegex = /--icon-([\w-]+)\s*:/g;
const rawNames = new Set<string>();
for (const m of css.matchAll(tokenRegex)) {
  rawNames.add(m[1]);
}

// Convert kebab-case token suffix to camelCase prop name
// e.g. "accent-purple" → "accentPurple"
// Exception: "on-light-surface" / "on-dark-surface" stay kebab-case (established
// API convention, inherited from the former "on-warning")
const KEEP_KEBAB = new Set(["on-light-surface", "on-dark-surface"]);

// REASON: tokens 0.20+ split `--icon-brand` / `--icon-comete` into
// `-default` / `-boldest`. The `-default` level keeps the historical prop name
// ("brand", "comete") so the public IconColor API stays stable.
const DEFAULT_SUFFIX = "-default";

function toPropName(s: string): string {
  if (KEEP_KEBAB.has(s)) return s;
  const base = s.endsWith(DEFAULT_SUFFIX)
    ? s.slice(0, -DEFAULT_SUFFIX.length)
    : s;
  return base.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
}

// Build sorted list of { propName, tokenSuffix }
const colors = [...rawNames]
  .map((suffix) => ({ prop: toPropName(suffix), suffix }))
  .sort((a, b) => a.prop.localeCompare(b.prop));

console.log(`Found ${colors.length} icon color tokens:`);
for (const c of colors) {
  console.log(`  ${c.prop} → --icon-${c.suffix}`);
}

// ---------------------------------------------------------------------------
// 2. Generate icons.css

const cssLines = [
  "/* Auto-generated by scripts/sync-icon-colors.ts — do not edit manually */",
  "/* Maps icon color props to Comète design token CSS custom properties */",
  "",
  ...colors.map(
    (c) => `.comete-icon--${c.prop} {\n  color: var(--icon-${c.suffix});\n}`,
  ),
  "",
];

writeFileSync(ICONS_CSS_PATH, cssLines.join("\n"));
console.log(`\n✔ Written ${ICONS_CSS_PATH}`);

// ---------------------------------------------------------------------------
// 3. Patch ICON_COLORS / IconColor in types.ts

const types = readFileSync(TYPES_PATH, "utf-8");

const listMembers = colors.map((c) => `  "${c.prop}",`).join("\n");
const newBlock = `/** Couleurs d'icône disponibles, triées, dérivées des tokens \`--icon-*\` de comete-design-tokens. */
export const ICON_COLORS = [
${listMembers}
] as const;

export type IconColor = (typeof ICON_COLORS)[number];`;

// REASON: recognise both the current form (ICON_COLORS const + derived type,
// since 0.14.0) and the legacy form (plain `IconColor` string union, up to
// 0.13.0) so the script can migrate an old types.ts in one run.
const BLOCK_REGEX =
  /(?:\/\*\*[^\n]*\*\/\n)?export const ICON_COLORS = \[\n[\s\S]*?\] as const;\n\nexport type IconColor = \(typeof ICON_COLORS\)\[number\];|export type IconColor =\n(?:\s*\| "[^"]+")+;/;

const patched = types.replace(BLOCK_REGEX, newBlock);

if (patched === types) {
  console.error(
    "⚠ Could not find ICON_COLORS / IconColor in types.ts — skipping patch",
  );
} else {
  writeFileSync(TYPES_PATH, patched);
  console.log(`✔ Patched ICON_COLORS / IconColor in ${TYPES_PATH}`);
}
