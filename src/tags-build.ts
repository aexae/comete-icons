/**
 * Construction des tags de recherche des icônes (`src/tags.ts`).
 *
 * Logique pure, partagée par `scripts/sync-tags.ts` (écriture du fichier) et
 * `src/tags.test.ts` (vérifie que `src/tags.ts` est à jour). Non exporté par
 * le paquet.
 */

import { normalizeSearchText } from "./normalize";
import { parseCsv } from "./omnis-build";

/** Séparateur des tags dans la colonne « Tags » de `data/icon-tags.csv`. */
export const TAG_SEPARATOR = "|";

/**
 * Chemin d'accès à une fonctionnalité (« Plan. > Menu vacation ») : ne sert pas à
 * retrouver une icône, refusé dans les tags.
 */
const PATH_PATTERN = /[>›»→]/;

/** Rangée de `data/icon-tags.csv` : une icône et ses tags. */
export interface TagRow {
  name: string;
  tags: string[];
}

/**
 * Lit `data/icon-tags.csv` (colonnes « Nom » et « Tags », tags séparés par `|`).
 * Nettoie les espaces et retire les tags en double (comparaison sans accents ni casse).
 */
export function readTagRows(csv: string): TagRow[] {
  const [header, ...lines] = parseCsv(csv);
  if (!header) throw new Error("CSV vide");
  const nameCol = header.findIndex((h) => h.trim() === "Nom");
  const tagsCol = header.findIndex((h) => h.trim() === "Tags");
  if (nameCol < 0 || tagsCol < 0) {
    throw new Error("Colonnes « Nom » et « Tags » introuvables");
  }
  const rows: TagRow[] = [];
  const seen = new Set<string>();
  for (const line of lines) {
    const name = (line[nameCol] ?? "").trim();
    if (name === "") continue;
    if (seen.has(name)) throw new Error(`Icône en double : ${name}`);
    seen.add(name);
    const keys = new Set<string>();
    const tags: string[] = [];
    for (const raw of (line[tagsCol] ?? "").split(TAG_SEPARATOR)) {
      const tag = raw.replace(/\s+/g, " ").trim();
      const key = normalizeSearchText(tag);
      if (key === "" || keys.has(key)) continue;
      keys.add(key);
      tags.push(tag);
    }
    rows.push({ name, tags });
  }
  return rows;
}

/**
 * Vérifie que le CSV couvre exactement les icônes du paquet : un nom inconnu
 * (icône renommée ou supprimée), une icône sans rangée (icône ajoutée) ou un tag
 * en forme de chemin d'accès échoue.
 * Retourne les rangées triées par nom.
 */
export function buildTags(
  rows: readonly TagRow[],
  iconNames: ReadonlySet<string>,
): TagRow[] {
  const listed = new Set(rows.map((r) => r.name));
  const unknown = rows.filter((r) => !iconNames.has(r.name)).map((r) => r.name);
  const missing = [...iconNames].filter((n) => !listed.has(n));
  const errors: string[] = [];
  if (unknown.length > 0) {
    errors.push(`Noms absents du paquet : ${unknown.join(", ")}`);
  }
  if (missing.length > 0) {
    errors.push(
      `Icônes sans rangée dans data/icon-tags.csv : ${missing.join(", ")}`,
    );
  }
  const paths = rows.flatMap((r) =>
    r.tags.filter((t) => PATH_PATTERN.test(t)).map((t) => `${r.name} « ${t} »`),
  );
  if (paths.length > 0) {
    errors.push(`Tags en forme de chemin d'accès : ${paths.join(", ")}`);
  }
  if (errors.length > 0) throw new Error(errors.join("\n"));
  return [...rows].sort((a, b) => a.name.localeCompare(b.name, "en"));
}

/** Produit le contenu de `src/tags.ts`. */
export function renderTagsModule(rows: readonly TagRow[]): string {
  const lines = [
    "/* Auto-generated by scripts/sync-tags.ts — do not edit manually */",
    "/**",
    " * Tags de recherche de chaque icône : usages métier dans Comète, en plus du",
    " * nom technique (souvent hérité de Material Symbols).",
    " *",
    " * Source : `data/icon-tags.csv`. Mise à jour : `pnpm sync-tags`.",
    " */",
    'import type { IconName } from "./types";',
    "",
    "export const iconTags: Readonly<Record<IconName, readonly string[]>> = {",
  ];
  for (const row of rows) {
    const tags = row.tags.map((t) => JSON.stringify(t)).join(", ");
    lines.push(`  ${row.name}: [${tags}],`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

/** Produit le contenu normalisé de `data/icon-tags.csv`. */
export function renderTagsCsv(rows: readonly TagRow[]): string {
  const field = (value: string) =>
    /[;"\r\n]/.test(value) ? `"${value.replaceAll('"', '""')}"` : value;
  const body = rows
    .map((r) => `${r.name};${field(r.tags.join(` ${TAG_SEPARATOR} `))}`)
    .join("\n");
  return `Nom;Tags\n${body}\n`;
}
